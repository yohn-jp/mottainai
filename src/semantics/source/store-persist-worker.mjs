// 並行性/crash-injection テスト用の子プロセス worker。単一プロセス内の Promise.all では
// ファイルシステムの真の競合（fsync/rename の interleaving や SIGKILL による中断）を
// 再現しないため、実プロセスを複数同時起動し、同じ rootDir 上の semantic source ディレクトリを
// 共有させる（task.concurrency.test.ts と同じ方針）。
import { createComponentId } from "../ir/ids.js";
import { applySemanticTransaction } from "../enforcement/index.js";

const [, , optionsJson] = process.argv;
const options = JSON.parse(optionsJson);

function newComponentMutation(localId) {
  const id = createComponentId(localId);
  return {
    kind: "component",
    component: {
      kind: "component",
      id,
      name: localId,
      description: `Generated by the store-persist-worker for ${localId}.`,
      responsibility: `Provide isolated coverage for the generated component ${localId}.`,
      stability: "experimental",
      reviewLevel: "L1",
    },
  };
}

const mutations = options.newComponentIds.map((localId) => newComponentMutation(localId));

const request = {
  mutations,
  intent: "semantic-change",
  reason: `Declare the generated components for ${options.actor} deterministically.`,
  authorizedDeltaKinds: ["responsibility"],
  provenance: { actor: options.actor, issue: "866", task: "semantic-persist-atomicity" },
  ...(options.expectedSnapshotDigest === undefined ? {} : { expectedSnapshotDigest: options.expectedSnapshotDigest }),
};

if (options.signalReady) {
  process.stdout.write("READY\n");
}

const result = await applySemanticTransaction(options.rootDir, request);
process.stdout.write(
  `${JSON.stringify({
    ok: result.ok,
    diagnostics: result.ok ? [] : result.diagnostics.map((item) => item.code),
  })}\n`,
);
